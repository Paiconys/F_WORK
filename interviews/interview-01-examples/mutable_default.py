def func(x=[]):
    # ВАЖНО: список-дефолт создаётся ОДИН раз при определении функции
    x.append(1)
    print(x)


func()        # [1]          — использовали общий дефолт
func([1, 2])  # [1, 2, 1]    — свой список, дефолт не трогали
func()        # [1, 1]       — снова общий дефолт (там уже был 1)
func([2, 3])  # [2, 3, 1]    — снова свой список


# Безопасный паттерн:
def func_safe(x=None):
    if x is None:
        x = []
    x.append(1)
    print(x)
